"""Cautious overnight expansion for stubs + books + PAST foreign events.

Stubs: expands `needsReview` / `autoGenerated` / short-description characters
       by pulling archive cards + related events, then asks LM
       Studio for a 600-900 word Waluigi-voiced expansion. Keeps original ID,
       preserves summary, marks as expanded but leaves `needsReview` true for
       human pass.

Books: generates one new book at a time from the same lore context. Checks
       for duplicate title/id, validates against existing categories.

Past Events (foreign): proposes ONE past event OR battle for a nation OTHER
       THAN Mushroom Kingdom / Midlands. Writes to events.json or battles.json
       (500-1000 words, README / STORY_FORMAT_GUIDE compliant). Full calendar
       audit (722-1040 BF), nation check, word-count check, duplicate-title
       check. Uses lore_search for nation context. HistoricalTimeline.json is
       NOT touched — it would fill with junk (per author request).

All three can run together overnight, but intentionally cautious:
 - one LLM call per item, then saves immediately (crash-safe)
 - --limit, --sleep, --timeout, --dry-run
 - past events are written directly to events.json/battles.json with a
   `proposed: true`-style flag in description for promoter to verify.

Usage:
  python tools/expand-waluipedia.py --stubs --dry-run --limit 3
  python tools/expand-waluipedia.py --stubs --overnight --limit 10
  python tools/expand-waluipedia.py --books --limit 1
  python tools/expand-waluipedia.py --past-events --dry-run --limit 1
  python tools/expand-waluipedia.py --past-events --overnight --target 5
  python tools/expand-waluipedia.py --all --overnight   # stubs+books+past-events+codex

Codex is still owned by gen-mages-guild-code.py; this tool can optionally
drive it via --codex (shells out). Timeline flag is deprecated — use --past-events.
"""
